.macro LIBA32_EABI_MEMSET name
.text
.p2align 2
.global \name
.type \name, %function
\name:
    mov r3, r1
    mov r1, r2
    mov r2, r3
    svc #LIBA32ANDROID_A32_LIBC_MEMSET_SVC
    bx lr
.size \name, .-\name
.endm

.macro LIBA32_EABI_MEMCLR name
.text
.p2align 2
.global \name
.type \name, %function
\name:
    mov r2, r1
    mov r1, #0
    svc #LIBA32ANDROID_A32_LIBC_MEMSET_SVC
    bx lr
.size \name, .-\name
.endm

